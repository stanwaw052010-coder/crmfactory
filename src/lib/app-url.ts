/**
 * Базова адреса застосунку для посилань у листах.
 *
 * Свідомо БЕЗ звернення до заголовків запиту: цю функцію викликає і фоновий
 * воркер нагадувань, у якого запиту немає взагалі. Там, де запит є
 * (відновлення пароля, Stripe Checkout), лишається власний варіант із
 * підстановкою реального хоста — він точніший, коли змінна не задана.
 *
 * Порожній `NEXT_PUBLIC_APP_URL` у продакшені означає посилання в нікуди,
 * тому запасний варіант — локальна адреса розробки: у листі це одразу
 * впадає в око, тоді як гарний, але чужий домен — ні.
 */
export function appUrl(): string {
  const configured = process.env.NEXT_PUBLIC_APP_URL?.trim().replace(/\/+$/, "");
  return configured || "http://localhost:3001";
}
